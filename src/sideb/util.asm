; ============================================================
; 共通ユーティリティ: タイマ減算 / オブジェクトスロット検索 / 乱数
; ============================================================

; ------------------------------------------------------------
; 2 バイトカウンタ減算
; 入力: HL = カウンタアドレス (リトルエンディアン 2 バイト)
; 出力: カウンタを 1 減算 / 全 16bit が 0 になったとき Z=1
; 破壊: A, HL, F
; ------------------------------------------------------------
timer_dec:
        ld a,(hl)
        sub 1
        ld (hl),a
        inc hl
        ld a,(hl)
        sbc a,0
        ld (hl),a
        or a
        ret nz                          ; 上位バイトが残っていれば未満了
        dec hl
        ld a,(hl)
        or a                            ; 下位バイトを確認して Z を確定
        ret

; ------------------------------------------------------------
; 空きオブジェクトスロット検索
; 入力: A = 開始スロット番号, B = 探索スロット数
; 出力: CY=0 → IX = 空きスロット先頭 (O_LEN = 8 バイト構造体)
;       CY=1 → 空きなし (IX は探索範囲の末尾+1)
; 破壊: A, B, DE, IX, F (HL は保存)
; ------------------------------------------------------------
FIND_SLOT:
        push hl
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl                       ; スロット番号 x 8 (O_LEN)
        ld de,O_TBL
        add hl,de
        push hl
        pop ix                          ; IX = スロット先頭
        pop hl
FS_L:   ld a,(ix+0)
        or a
        ret z                           ; +0 = 0 (空き) を発見
        ld de,O_LEN
        add ix,de
        djnz FS_L
        scf
        ret

; ------------------------------------------------------------
; 簡易乱数 1 バイト
; 入力: なし
; 出力: A = 乱数 (R レジスタ xor フレームカウンタ), W_RAND 更新
; 破壊: A, B, F
; ------------------------------------------------------------
rand8:
        ld a,r
        ld b,a
        ld a,(W_TICK)
        xor b
        ld (W_RAND),a
        ret
